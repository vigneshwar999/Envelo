// One-shot compiler: contracts/SealedInvoiceRegistry.sol -> src/chain/registryArtifact.ts
// Run with: node scripts/compile-contract.mjs   (from artifacts/api-server)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = readFileSync(join(root, "contracts", "SealedInvoiceRegistry.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "SealedInvoiceRegistry.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const contract = output.contracts["SealedInvoiceRegistry.sol"].SealedInvoiceRegistry;
const abi = contract.abi;
const bytecode = "0x" + contract.evm.bytecode.object;

const ts = `// Generated by scripts/compile-contract.mjs - do not edit by hand.
// Recompile with: node scripts/compile-contract.mjs
export const REGISTRY_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const REGISTRY_BYTECODE = ${JSON.stringify(bytecode)} as const;
`;

mkdirSync(join(root, "src", "chain"), { recursive: true });
writeFileSync(join(root, "src", "chain", "registryArtifact.ts"), ts);
console.log("Wrote src/chain/registryArtifact.ts (abi entries:", abi.length + ", bytecode bytes:", (bytecode.length - 2) / 2 + ")");
